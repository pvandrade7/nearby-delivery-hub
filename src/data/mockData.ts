export const getProductSeller = (product: Product) => {
  if (product.storeId) {
    const store = stores.find((s) => s.id === product.storeId);
    return store ? {
      type: "store" as const,
      id: store.id, name: store.name, image: store.image,
      rating: store.rating, reviews: store.reviews,
      description: store.description,
      location: store.distance,
      responseTime: store.deliveryTime,
      verified: store.verificationStatus === "verificado",
      accountInfo: "Loja oficial verificada",
    } : null;
  }
  if (product.sellerId) {
    const seller = individualSellers.find((s) => s.id === product.sellerId);
    return seller ? {
      type: "individual" as const,
      id: seller.id, name: seller.name, avatar: seller.avatar,
      rating: seller.rating, reviews: seller.reviews,
      description: seller.accountInfo,
      location: seller.city,
      responseTime: seller.responseTime,
      verified: false,
      accountInfo: seller.memberSince,
    } : null;
  }
  return null;
};

