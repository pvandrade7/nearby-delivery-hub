export type Category = { id: string; name: string; emoji: string };

export type Store = {
  id: string;
  name: string;
  category: string;
  /** Cidade onde a loja está localizada — usada para regionalização */
  city: string;
  rating: number;
  reviews: number;
  distance: string;
  deliveryTime: string;
  image: string;
  description: string;
  freeShippingFrom?: number;
  sellerType: "cnpj" | "empreendedor" | "comum";
  verificationStatus: "nao_verificado" | "pendente" | "verificado" | "rejeitado";
  verificationType?: "cnpj" | "manual";
  cnpj?: string;
  address?: string;
  /** true = comércio local/urbano de bairro; omitido/false = grande rede nacional */
  isLocal?: boolean;
  /** URL do logotipo oficial (preferencialmente PNG com transparência) */
  logo?: string;
  /** Cor principal da marca em hex — usada no fallback quando o logo não carrega */
  brandColor?: string;
};

export type IndividualSeller = {
  id: string;
  name: string;
  avatar: string;
  city: string;
  memberSince: string;
  responseTime: string;
  accountInfo: string;
  rating: number;
  reviews: number;
  verificationStatus: "nao_verificado" | "pendente" | "verificado" | "rejeitado";
};

export type Product = {
  id: string;
  storeId?: string;
  sellerId?: string;
  name: string;
  price: number;
  originalPrice?: number;
  description: string;
  category: string;
  image: string;
  popular?: boolean;
  onSale?: boolean;
};

export type OrderStatus = "confirmado" | "preparando" | "saiu" | "entregue";

export type Order = {
  id: string;
  storeId: string;
  storeName: string;
  items: { productId: string; name: string; quantity: number; price: number }[];
  total: number;
  status: OrderStatus;
  customer: string;
  address: string;
  createdAt: string;
};

